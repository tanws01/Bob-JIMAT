/* ==========================================================================
   JIMAT - Data layer (REAL DOSM PriceCatcher open data)
   --------------------------------------------------------------------------
   Adapts the baked snapshot (window.JIMAT_SNAPSHOT, generated by
   build/build_snapshot.py from data.gov.my) into the shape the engine and
   controller use. Everything here is REAL:
     - items      : real DOSM PriceCatcher tracked items (name, unit)
     - premises   : real store name, address, state, district
     - prices     : real monthly average price per premise (RM)
   District coordinates are geocoded approximations used only to estimate a
   travel radius; exact routing is delegated to Google Maps / Waze.

   No Databricks, no Git. DOSM public open data only.
   ========================================================================== */
(function () {
  "use strict";

  var SNAP = window.JIMAT_SNAPSHOT || { meta: {}, items: [], states: [], premises: [] };

  /* ---- Products (from real DOSM items) ---------------------------------- */
  var PRODUCTS = SNAP.items.map(function (it) {
    return {
      id: it.id, code: it.code, name: it.short || it.name, full: it.full || it.name,
      emoji: it.emoji, unit: it.unit, base: it.base, cat: it.cat, asof: it.asof,
    };
  });

  /* ---- Categories (real DOSM item groups) ------------------------------- */
  var CATEGORIES = SNAP.categories || [];

  /* ---- Convenience rating derived from real premise type ---------------- */
  function convenienceOf(type) {
    switch (type) {
      case "Hypermarket": return 5;
      case "Supermarket": return 5;
      case "Convenience": return 4;
      case "Mini Market": return 4;
      case "Grocery Store": return 3;
      case "Wholesale": return 3;
      case "Wet Market": return 2;
      default: return 3;
    }
  }

  /* ---- Locations (real states -> districts, with centroids) ------------- */
  var STATES = SNAP.states;

  function stateByKey(k) { return STATES.find(function (s) { return s.key === k; }); }
  function districtByKey(sk, dk) {
    var s = stateByKey(sk);
    return s ? s.districts.find(function (d) { return d.key === dk; }) : null;
  }
  function areaName(sk, dk) {
    var s = stateByKey(sk), d = districtByKey(sk, dk);
    if (!s) return "";
    return d ? d.name + ", " + s.name : s.name;
  }

  /* ---- Distance (haversine, km) ----------------------------------------- */
  function haversine(aLat, aLon, bLat, bLon) {
    var R = 6371, toR = Math.PI / 180;
    var dLat = (bLat - aLat) * toR, dLon = (bLon - aLon) * toR;
    var s = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
      Math.cos(aLat * toR) * Math.cos(bLat * toR) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
    return 2 * R * Math.asin(Math.min(1, Math.sqrt(s)));
  }

  // Turn a raw premise into a store object with distance from (lat, lon).
  function toStore(p, lat, lon) {
    return {
      id: "p" + p.code, code: p.code, name: p.name, type: p.type, address: p.address,
      state: p.state, district: p.district, lat: p.lat, lon: p.lon,
      distanceKm: haversine(lat, lon, p.lat, p.lon),
      convenience: convenienceOf(p.type),
      prices: p.prices || {},
    };
  }

  /* Premises within the travel radius of a point (the user's district
     centroid). Falls back to the nearest handful if the radius is empty.
     Capped so the optimiser and UI stay fast. */
  var MAX_STORES = 60;
  function candidatePremises(lat, lon, radiusKm) {
    if (lat == null || lon == null) return [];
    var all = SNAP.premises.map(function (p) { return toStore(p, lat, lon); })
      .sort(function (a, b) { return a.distanceKm - b.distanceKm; });
    var within = all.filter(function (s) { return s.distanceKm <= radiusKm; });
    if (within.length < 3) within = all.slice(0, 6);
    return within.slice(0, MAX_STORES);
  }

  // How many premises are in range (for the location preview).
  function storesInRange(lat, lon, radiusKm) {
    if (lat == null || lon == null) return 0;
    return SNAP.premises.reduce(function (n, p) {
      return n + (haversine(lat, lon, p.lat, p.lon) <= radiusKm ? 1 : 0);
    }, 0);
  }

  /* ---- Front-end presets (not part of DOSM) ----------------------------- */
  var HOUSEHOLDS = {
    single: { label: "Just me",    emoji: "\u{1F464}", factor: 0.5 },
    couple: { label: "Couple",     emoji: "\u{1F46B}", factor: 1.0 },
    family: { label: "Family",     emoji: "\u{1F46A}", factor: 1.6 },
    large:  { label: "Big family", emoji: "\u{1F468}\u{200D}\u{1F469}\u{200D}\u{1F467}\u{200D}\u{1F466}", factor: 2.2 },
  };

  var BUDGET_PRESETS = { single: 350, couple: 650, family: 1000, large: 1350 };

  // Rough petrol + time cost per km (return trip factored in the engine).
  var TRAVEL_COST_PER_KM = 0.55;
  var TRIPS_PER_MONTH = 4;

  window.JIMAT_DATA = {
    META: SNAP.meta,
    PRODUCTS: PRODUCTS,
    CATEGORIES: CATEGORIES,
    STATES: STATES,
    HOUSEHOLDS: HOUSEHOLDS,
    BUDGET_PRESETS: BUDGET_PRESETS,
    TRAVEL_COST_PER_KM: TRAVEL_COST_PER_KM,
    TRIPS_PER_MONTH: TRIPS_PER_MONTH,
    areaName: areaName,
    stateByKey: stateByKey,
    districtByKey: districtByKey,
    candidatePremises: candidatePremises,
    storesInRange: storesInRange,
    haversine: haversine,
  };
})();
